'use server';

import { revalidatePath } from 'next/cache';
import { requireUser } from '@/lib/auth';
import * as applicationsRepo from '@/lib/repos/applicationsRepo';
import * as statusHistoryRepo from '@/lib/repos/statusHistoryRepo';
import * as usersRepo from '@/lib/repos/usersRepo';
import { generateApplicationToken } from '@/lib/tokens';
import type { ApplicationStatus } from '@/types/db';
import type { ActionResult } from '@/actions/settingsActions';

export type CreateLinkResult = ActionResult & { url?: string; token?: string };

export async function createApplicationLinkAction(): Promise<CreateLinkResult> {
  try {
    const user = await requireUser();

    if (user.isBlocked) {
      return {
        ok: false,
        error: `Your account is currently blocked from originating new loan links. ${user.blockedReason ? `Reason: ${user.blockedReason}` : 'Please contact your Relationship Manager or Admin.'}`,
      };
    }

    const token = generateApplicationToken();
    const isPartner = user.role === 'CHANNEL_PARTNER';
    const isRM = user.role === 'RELATIONSHIP_MANAGER';

    const application = applicationsRepo.createApplicationLink({
      token,
      branchId: user.branchId,
      createdById: user.id,
      channelPartnerId: isPartner ? user.id : undefined,
      channelPartnerName: isPartner ? user.name : undefined,
      relationshipManagerId: isPartner ? (user.assignedRmId || null) : isRM ? user.id : null,
      relationshipManagerName: isPartner ? (user.assignedRmName || null) : isRM ? user.name : null,
      tenantId: user.tenantId,
    });

    statusHistoryRepo.addStatusHistory({
      applicationId: application.id,
      status: 'LINK_SHARED',
      note: isPartner
        ? `Customer application link generated by Channel Partner ${user.name}.`
        : `Customer application link generated by ${user.name} (${user.role}).`,
      changedById: user.id,
    });

    const base =
      process.env.APP_BASE_URL ||
      process.env.RENDER_EXTERNAL_URL ||
      process.env.NEXTAUTH_URL ||
      'https://quicfinsure.onrender.com';
    const cleanBase = base.replace(/\/$/, '');
    const url = `${cleanBase}/apply/${token}`;

    revalidatePath('/branch/requests');
    return { ok: true, url, token };
  } catch {
    return { ok: false, error: 'Could not generate a link. Please try again.' };
  }
}

const VALID_STATUSES: ApplicationStatus[] = [
  'LINK_SHARED',
  'DOCUMENTS_IN',
  'SENT_TO_BANK',
  'DOCUMENTS_REQUIRED',
  'APPROVED',
  'CUSTOMER_ACCEPTED',
  'DISBURSED',
  'REJECTED',
];

export async function updateApplicationStatusAction(
  applicationId: string,
  status: ApplicationStatus,
  note?: string
): Promise<ActionResult> {
  try {
    const user = await requireUser();
    const application = applicationsRepo.getApplicationById(applicationId);
    if (!application) return { ok: false, error: 'Application not found.' };
    if (user.role === 'CHANNEL_PARTNER') {
      if (application.channelPartnerId !== user.id && application.createdById !== user.id) {
        return { ok: false, error: 'Unauthorized: This application belongs to another partner.' };
      }
    } else if (user.role === 'RELATIONSHIP_MANAGER') {
      const isDirect = application.relationshipManagerId === user.id || application.createdById === user.id;
      let isPartnerApp = false;
      if (application.channelPartnerId) {
        const partner = usersRepo.getUserById(application.channelPartnerId);
        if (partner && partner.assignedRmId === user.id) isPartnerApp = true;
      }
      if (!isDirect && !isPartnerApp) {
        return { ok: false, error: 'Unauthorized: You can only update applications from your assigned Channel Partners.' };
      }
    } else if (
      user.role !== 'ADMIN' &&
      user.role !== 'OPERATIONS' &&
      user.role !== 'CENTRAL_SUPPORT' &&
      application.branchId !== user.branchId
    ) {
      return { ok: false, error: 'This application belongs to a different branch.' };
    }
    if (!VALID_STATUSES.includes(status)) return { ok: false, error: 'Invalid status.' };

    applicationsRepo.updateApplicationStatus(applicationId, status);
    statusHistoryRepo.addStatusHistory({ applicationId, status, note: note || null, changedById: user.id });

    revalidatePath('/branch/requests');
    revalidatePath(`/branch/requests/${applicationId}`);
    return { ok: true, message: 'Status updated.' };
  } catch {
    return { ok: false, error: 'Could not update status. Please try again.' };
  }
}
