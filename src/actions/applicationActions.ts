function safeRevalidate(path: string) {
  try {
    revalidatePath(path);
  } catch (err) {
    console.warn(`[safeRevalidate] Warning revalidating ${path}:`, err);
  }
}

export type CreateLinkResult = ActionResult & { url?: string; token?: string };

export async function createApplicationLinkAction(loanType?: LoanType): Promise<CreateLinkResult> {
  try {
    const user = await getAuthenticatedUser();
    if (!user) {
      return {
        ok: false,
        error: 'Your session has expired. Please log in again to generate loan links.',
      };
    }

    if (user.isBlocked) {
      return {
        ok: false,
        error: `Your account is currently blocked from originating new loan links. ${user.blockedReason ? `Reason: ${user.blockedReason}` : 'Please contact your Relationship Manager or Admin.'}`,
      };
    }

    const token = generateApplicationToken();
    const isPartner = user.role === 'CHANNEL_PARTNER';
    const isRM = user.role === 'RELATIONSHIP_MANAGER';

    const application = applicationsRepo.createApplicationLink({
      token,
      branchId: user.branchId || 'default',
      createdById: user.id,
      channelPartnerId: isPartner ? user.id : undefined,
      channelPartnerName: isPartner ? user.name : undefined,
      relationshipManagerId: isPartner ? (user.assignedRmId || null) : isRM ? user.id : null,
      relationshipManagerName: isPartner ? (user.assignedRmName || null) : isRM ? user.name : null,
      tenantId: user.tenantId || 'default',
    });

    statusHistoryRepo.addStatusHistory({
      applicationId: application.id,
      status: 'LINK_SHARED',
      note: isPartner
        ? `Customer application link generated by Channel Partner ${user.name}${loanType ? ` for ${LOAN_TYPE_LABELS[loanType] || loanType}` : ''}.`
        : `Customer application link generated by ${user.name} (${user.role})${loanType ? ` for ${LOAN_TYPE_LABELS[loanType] || loanType}` : ''}.`,
      changedById: user.id,
    });

    const base =
      process.env.APP_BASE_URL ||
      process.env.RENDER_EXTERNAL_URL ||
      process.env.NEXTAUTH_URL ||
      'https://quicfinsure.onrender.com';
    const cleanBase = base.replace(/\/$/, '');
    const url = `${cleanBase}/apply/${token}${loanType ? `?loanType=${loanType}` : ''}`;

    safeRevalidate('/dashboard');
    safeRevalidate('/branch/requests');

    // MAIN SYSTEM SYNC: Commit immediately to Neon PostgreSQL
    await syncDatabase();

    return { ok: true, url, token };
  } catch (err) {
    console.error('[createApplicationLinkAction] error:', err);
    return {
      ok: false,
      error: (err as Error).message || 'Could not generate a link. Please try again.',
    };
  }
}

const VALID_STATUSES: ApplicationStatus[] = [
  'LINK_SHARED',
  'DOCUMENTS_IN',
  'SENT_TO_BANK',
  'DOCUMENTS_REQUIRED',
  'APPROVED',
  'CUSTOMER_ACCEPTED',
  'DISBURSED',
  'REJECTED',
];

export async function updateApplicationStatusAction(
  applicationId: string,
  status: ApplicationStatus,
  note?: string
): Promise<ActionResult> {
  try {
    const user = await getAuthenticatedUser();
    if (!user) {
      return { ok: false, error: 'Your session has expired. Please sign in again.' };
    }
    const application = applicationsRepo.getApplicationById(applicationId);
    if (!application) return { ok: false, error: 'Application not found.' };
    if (user.role === 'CHANNEL_PARTNER') {
      if (application.channelPartnerId !== user.id && application.createdById !== user.id) {
        return { ok: false, error: 'Unauthorized: This application belongs to another partner.' };
      }
    } else if (user.role === 'RELATIONSHIP_MANAGER') {
      const isDirect = application.relationshipManagerId === user.id || application.createdById === user.id;
      let isPartnerApp = false;
      if (application.channelPartnerId) {
        const partner = usersRepo.getUserById(application.channelPartnerId);
        if (partner && partner.assignedRmId === user.id) isPartnerApp = true;
      }
      if (!isDirect && !isPartnerApp) {
        return { ok: false, error: 'Unauthorized: You can only update applications from your assigned Channel Partners.' };
      }
    } else if (
      user.role !== 'ADMIN' &&
      user.role !== 'OPERATIONS' &&
      user.role !== 'CENTRAL_SUPPORT' &&
      application.branchId !== user.branchId
    ) {
      return { ok: false, error: 'This application belongs to a different branch.' };
    }
    if (!VALID_STATUSES.includes(status)) return { ok: false, error: 'Invalid status.' };

    applicationsRepo.updateApplicationStatus(applicationId, status);
    statusHistoryRepo.addStatusHistory({ applicationId, status, note: note || null, changedById: user.id });

    if (status === 'REJECTED') {
      try {
        await notifyTouchpoint08_LoanRejected(
          application,
          note || 'Application rejected by operations.',
          { tenantId: application.tenantId }
        );
      } catch (err) {
        console.warn('[updateApplicationStatusAction] Error triggering Touchpoint 08:', err);
      }
    }

    safeRevalidate('/dashboard');
    safeRevalidate('/branch/requests');
    safeRevalidate(`/branch/requests/${applicationId}`);

    // MAIN SYSTEM SYNC: Commit immediately to Neon PostgreSQL
    await syncDatabase();

    return { ok: true, message: 'Status updated.' };
  } catch (err) {
    console.error('[updateApplicationStatusAction] error:', err);
    return { ok: false, error: (err as Error).message || 'Could not update status. Please try again.' };
  }
}

export type SubmitDirectLoanResult = {
  ok: boolean;
  error?: string;
  applicationId?: string;
  token?: string;
  url?: string;
  status?: ApplicationStatus;
  emailSent?: boolean;
};

export async function submitDirectPartnerLoanAction(formData: FormData): Promise<SubmitDirectLoanResult> {
  try {
    let user = await getAuthenticatedUser();
    if (!user) {
      const originatorUserId = String(formData.get('originatorUserId') || formData.get('advisorId') || '').trim();
      const originatorEmail = String(formData.get('originatorEmail') || formData.get('advisorEmail') || '').trim();
      if (originatorUserId) {
        const u = usersRepo.getUserById(originatorUserId);
        if (u && u.active && !u.isBlocked) {
          user = { ...u, branchName: u.branchName || 'Head Office' };
        }
      }
      if (!user && originatorEmail) {
        const u = usersRepo.getUserByEmail(originatorEmail);
        if (u && u.active && !u.isBlocked) {
          user = { ...u, branchName: u.branchName || 'Head Office' };
        }
      }
    }

    if (!user) {
      return {
        ok: false,
        error: 'Your session has expired. Please log in again to submit loan requirements.',
      };
    }

    if (user.isBlocked) {
      return {
        ok: false,
        error: `Your account is currently blocked from originating new loan cases. ${
          user.blockedReason ? `Reason: ${user.blockedReason}` : 'Please contact your Relationship Manager or Admin.'
        }`,
      };
    }

    const fullName = String(formData.get('fullName') || '').trim();
    const mobile = String(formData.get('mobile') || '').trim();
    const email = String(formData.get('email') || '').trim();
    const loanType = String(formData.get('loanType') || '').trim() as LoanType;
    const loanAmount = Number(formData.get('loanAmount') || 0);
    const rawMonthlyIncome = formData.get('monthlyIncome');
    const monthlyIncome = rawMonthlyIncome !== null && rawMonthlyIncome !== '' ? Number(rawMonthlyIncome) : undefined;
    const rawExistingEmi = formData.get('existingEmi');
    const existingEmi = rawExistingEmi !== null && rawExistingEmi !== '' ? Number(rawExistingEmi) : undefined;
    const rawTenureYears = formData.get('tenureYears');
    const rawTenureMonths = formData.get('tenureMonths');
    const tenureMonths = rawTenureYears
      ? Number(rawTenureYears) * 12
      : rawTenureMonths
      ? Number(rawTenureMonths)
      : undefined;
    const panNumber = String(formData.get('panNumber') || '').trim().toUpperCase();
    const aadhaarNumber = String(formData.get('aadhaarNumber') || '').trim().replace(/\s+/g, '');

    if (!fullName) {
      return { ok: false, error: 'Customer full name is required.' };
    }
    if (!/^[0-9]{10}$/.test(mobile)) {
      return { ok: false, error: 'Please enter a valid 10-digit mobile number.' };
    }
    if (!loanType) {
      return { ok: false, error: 'Please select a loan category.' };
    }
    if (!loanAmount || loanAmount <= 0) {
      return { ok: false, error: 'Please enter a valid loan amount required.' };
    }

    if (panNumber && !/^[A-Z]{5}[0-9]{4}[A-Z]{1}$/.test(panNumber)) {
      return { ok: false, error: 'Please enter a valid 10-character PAN number (e.g. ABCDE1234F).' };
    }
    if (aadhaarNumber && !/^[0-9]{12}$/.test(aadhaarNumber)) {
      return { ok: false, error: 'Please enter a valid 12-digit Aadhaar number.' };
    }

    const panFile = formData.get('panFile');
    const aadhaarFile = formData.get('aadhaarFile');
    const hasUploadedDocs =
      (panFile instanceof File && panFile.size > 0) || (aadhaarFile instanceof File && aadhaarFile.size > 0);
    const initialStatus: ApplicationStatus = hasUploadedDocs ? 'DOCUMENTS_IN' : 'LINK_SHARED';

    // Direct partner/agent loan origination
    const application = applicationsRepo.createDirectPartnerApplication({
      advisorId: user.id,
      advisor: user,
      fullName,
      mobile,
      email: email || undefined,
      loanType,
      loanAmount,
      monthlyIncome,
      existingEmi,
      tenureMonths,
      panNumber: panNumber || undefined,
      aadhaarNumber: aadhaarNumber || undefined,
      status: initialStatus,
    });

    // Save PAN document if provided
    if (panFile instanceof File && panFile.size > 0) {
      try {
        const savedPan = await saveUploadedFile(panFile, application.id);
        documentsRepo.addDocument({
          applicationId: application.id,
          category: 'PAN_CARD',
          label: `PAN Card (${panNumber || 'Applicant'})`,
          ...savedPan,
        });
      } catch (uploadErr) {
        console.warn('[DirectPartnerLoan] PAN file upload failed:', uploadErr);
      }
    }

    // Save Aadhaar document if provided
    if (aadhaarFile instanceof File && aadhaarFile.size > 0) {
      try {
        const savedAadhaar = await saveUploadedFile(aadhaarFile, application.id);
        documentsRepo.addDocument({
          applicationId: application.id,
          category: 'AADHAAR_CARD',
          label: `Aadhaar Card (${aadhaarNumber ? `...${aadhaarNumber.slice(-4)}` : 'Applicant'})`,
          ...savedAadhaar,
        });
      } catch (uploadErr) {
        console.warn('[DirectPartnerLoan] Aadhaar file upload failed:', uploadErr);
      }
    }

    // Record status history
    statusHistoryRepo.addStatusHistory({
      applicationId: application.id,
      status: initialStatus,
      note: `Customer loan request submitted by ${user.name} (${user.role}). PAN: ${panNumber || 'N/A'}, Aadhaar: ${
        aadhaarNumber || 'N/A'
      }.${hasUploadedDocs ? ' Self-attested KYC documents attached.' : ' Staged in Link Shared bucket.'}`,
      changedById: user.id,
    });

    const base =
      process.env.APP_BASE_URL ||
      process.env.RENDER_EXTERNAL_URL ||
      process.env.NEXTAUTH_URL ||
      'https://quicfinsure.onrender.com';
    const cleanBase = base.replace(/\/$/, '');
    const url = `${cleanBase}/apply/${application.token}`;

    // MAIL SYSTEM DISPATCH: Send notification emails to branch and customer
    let emailDispatched = false;
    // Trigger Touchpoint 01 Notifications (In-App to RM & Ops + Customer & Branch Emails)
    try {
      await notifyTouchpoint01_CustomerSubmitted(application, { tenantId: user.tenantId });
      emailDispatched = true;
    } catch (notifErr) {
      console.warn('[DirectPartnerLoan] Error triggering Touchpoint 01 notifications:', notifErr);
    }

    // MAIN SYSTEM SYNC: Ensure database persistence is completed before returning
    await syncDatabase();

    safeRevalidate('/dashboard');
    safeRevalidate('/branch/requests');
    safeRevalidate(`/branch/requests/${application.id}`);

    return {
      ok: true,
      applicationId: application.id,
      token: application.token,
      url,
      status: initialStatus,
      emailSent: emailDispatched,
    };
  } catch (err) {
    console.error('[submitDirectPartnerLoanAction] error:', err);
    return {
      ok: false,
      error: (err as Error).message || 'Failed to submit loan requirement. Please try again.',
    };
  }
}
